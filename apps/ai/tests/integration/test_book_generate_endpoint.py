@pytest.mark.integration
async def test_book_generate_foreign_chapter_is_422(
    client: AsyncClient, auth_headers: dict, db_session: AsyncSession
):
    """A chapter_id belonging to a DIFFERENT book must be rejected (422) and no
    job may leak. Mutation guard for the membership check."""
    book_id, _project_id, chapter_ids = await _make_book(
        db_session, chapters=[[(1, None)]]
    )
    _other_book, _p2, other_chapter_ids = await _make_book(
        db_session, chapters=[[(1, None)]]
    )
    with patch("app.api.v1.ai.enqueue_book_generation_job") as mock_enqueue:
        resp = await client.post(
            f"/api/v1/ai/books/{book_id}/generate",
            json={
                "chapter_ids": [str(chapter_ids[0]), str(other_chapter_ids[0])]
            },
            headers=auth_headers,
        )
    assert resp.status_code == 422
    mock_enqueue.assert_not_called()
    jobs = (
        (
            await db_session.execute(
                select(GenerationJob).where(
                    GenerationJob.job_type == JobType.BOOK_GENERATE
                )
            )
        )
        .scalars()
        .all()
    )
    assert jobs == []


