@pytest.mark.integration
async def test_book_generate_enqueue_failure_marks_job_failed(
    client: AsyncClient, auth_headers: dict, db_session: AsyncSession
):
    """If enqueue raises (Redis down), the job is persisted FAILED (never stuck
    PENDING) and a sanitized 502 is returned (no broker URL/secret echoed)."""
    book_id, _project_id, _chapter_ids = await _make_book(
        db_session, chapters=[[(1, None)]]
    )
    with patch(
        "app.api.v1.ai.enqueue_book_generation_job",
        side_effect=RuntimeError("redis://:s3cr3t-leak-xyz@broker:6379 refused"),
    ):
        resp = await client.post(
            f"/api/v1/ai/books/{book_id}/generate",
            json={},
            headers=auth_headers,
        )
    assert resp.status_code == 502
    assert "s3cr3t-leak-xyz" not in resp.text
    assert "broker:6379" not in resp.text
    job = (
        await db_session.execute(
            select(GenerationJob).where(
                GenerationJob.job_type == JobType.BOOK_GENERATE
            )
        )
    ).scalar_one()
    assert job.status == JobStatus.FAILED
